/**
 * 더미 피드 데이터 생성 함수
 * - 총 15개의 피드 아이템 생성
 * - 약 60%는 이미지 포함, 40%는 텍스트만
 */
const generateDummyFeeds = (): FeedItem[] => {
  return Array.from({ length: 15 }, (_, index) => {
    /** 이미지 포함 여부 (약 60% 확률) */
    const hasImage = index % 5 !== 0 && index % 5 !== 3;

    return {
      id: faker.string.uuid(),
      user: {
        nickname: faker.person.lastName() + faker.person.firstName(),
        avatarUrl: faker.image.urlPicsumPhotos({ width: 80, height: 80 }),
      },
      expertStyle: EXPERT_STYLES[index % EXPERT_STYLES.length],
      dreamContent: DREAM_CONTENTS[index % DREAM_CONTENTS.length],
      aiAnalysisSummary: AI_ANALYSIS_SUMMARIES[index % AI_ANALYSIS_SUMMARIES.length],
      imageUrl: hasImage
        ? faker.image.urlPicsumPhotos({ width: 600, height: 400 })
        : null,
      createdAt: faker.date.recent({ days: 30 }),
    };
  });
};

/** 정렬된 더미 피드 데이터 (최신순) */
